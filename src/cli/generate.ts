// TypeScript generation from an sp-laravel-api OpenAPI document. Pure (no I/O), so it is unit-testable;
// the CLI around it lives in typegen.ts.

/** A generation failure with a one-line, secret-free message (the CLI prints it and exits 2). */
export class TypegenError extends Error {
  /** Creates the error; `message` must be a single line. */
  constructor(message: string) {
    super(message);
    this.name = 'TypegenError';
  }
}

type Schema = Record<string, unknown>;

const HEADER = '// Generated by sp-laravel-api typegen — do not edit.';
const REF_PREFIX = '#/components/schemas/';
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function isRecord(v: unknown): v is Schema {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

const byKey = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** Single-quoted TypeScript string literal. */
function quote(s: string): string {
  return `'${s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029')}'`;
}

/** A schema name as a TypeScript identifier. */
function ident(name: string): string {
  const s = name.replace(/[^A-Za-z0-9_$]/g, '_');
  return /^[0-9]/.test(s) ? `_${s}` : s;
}

const propKey = (k: string): string => (IDENT.test(k) ? k : quote(k));

/** Text safe inside a one-line block comment. */
const commentText = (s: string): string => s.replace(/\*\//g, '*\\/').replace(/\s*[\r\n]+\s*/g, ' ').trim();

/** `sp-laravel-api`'s `OpenApiService::schemaName()`: `str_replace(['-', ' '], '_', ucwords(strtolower($table)))`. */
export function schemaName(table: string): string {
  return table
    .toLowerCase()
    .replace(/(^|[ \t\r\n\f\v])([a-z])/g, (_m, sep: string, c: string) => sep + c.toUpperCase())
    .replace(/[- ]/g, '_');
}

function literal(v: unknown): string {
  if (typeof v === 'string') return quote(v);
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (v === null) return 'null';
  return 'unknown';
}

function union(parts: string[]): string {
  const unique = [...new Set(parts)];
  if (unique.includes('unknown')) return 'unknown';
  return unique.join(' | ');
}

/** `t | null`, unless `t` is `unknown` or already ends in `null`. */
function withNull(t: string): string {
  return t === 'unknown' || t.split(' | ').includes('null') ? t : `${t} | null`;
}

/** How a `{Name}Read` / `{Name}Write` table schema is emitted (see `Generator.members`). */
interface TableMode {
  kind: 'read' | 'write';
  /** Properties added from the full `{Name}` schema (only for those the table schema lacks). */
  extra?: Schema;
}

/** Wraps a type that would mis-parse as an array element or intersection member. */
const group = (t: string): string => (/[|&]/.test(t) && !/^[{(]/.test(t) ? `(${t})` : t);

class Generator {
  private readonly schemas: Record<string, unknown>;
  /** Named schemas reached through `$ref`, emitted after the table schemas. */
  readonly referenced = new Set<string>();

  constructor(schemas: Record<string, unknown>) {
    this.schemas = schemas;
  }

  /** The TypeScript type of a schema. `indent` is the indentation of the line the type starts on. */
  type(schema: unknown, indent: string, omitReadOnly = false): string {
    if (!isRecord(schema)) return 'unknown';
    const t = this.baseType(schema, indent, omitReadOnly);
    return schema.nullable === true ? withNull(t) : t;
  }

  private ref(ref: unknown): string {
    if (typeof ref !== 'string' || !ref.startsWith(REF_PREFIX)) return 'unknown';
    const name = ref.slice(REF_PREFIX.length);
    if (!Object.prototype.hasOwnProperty.call(this.schemas, name)) {
      throw new TypegenError(`unresolved $ref ${quote(ref)}`);
    }
    this.referenced.add(name);
    return ident(name);
  }

  private baseType(schema: Schema, indent: string, omitReadOnly: boolean): string {
    if (schema.$ref !== undefined) return this.ref(schema.$ref);
    if (Array.isArray(schema.enum) && schema.enum.length > 0) return union(schema.enum.map(literal));
    if (schema.const !== undefined) return literal(schema.const);
    if (Array.isArray(schema.allOf) && schema.allOf.length > 0) {
      return schema.allOf.map((s) => group(this.type(s, indent))).join(' & ');
    }
    for (const key of ['oneOf', 'anyOf'] as const) {
      const list = schema[key];
      if (Array.isArray(list) && list.length > 0) return union(list.map((s) => this.type(s, indent)));
    }
    const types = Array.isArray(schema.type) ? schema.type : schema.type === undefined ? [] : [schema.type];
    if (types.length === 0) {
      return isRecord(schema.properties) || schema.additionalProperties !== undefined ? this.object(schema, indent, omitReadOnly) : 'unknown';
    }
    return union(types.map((t) => this.single(t, schema, indent, omitReadOnly)));
  }

  private single(t: unknown, schema: Schema, indent: string, omitReadOnly: boolean): string {
    switch (t) {
      case 'string':
        return 'string';
      case 'integer':
      case 'number':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'null':
        return 'null';
      case 'array': {
        const item = schema.items === undefined ? 'unknown' : this.type(schema.items, indent);
        return /^[A-Za-z0-9_$]+$/.test(item) ? `${item}[]` : `Array<${item}>`;
      }
      case 'object':
        return this.object(schema, indent, omitReadOnly);
      default:
        return 'unknown';
    }
  }

  /**
   * Property lines of an object schema, sorted by name. With `table` (a `{Name}Read` / `{Name}Write` schema),
   * the backend's conventions apply: `required` means "non-nullable column", so every other property is
   * `name?: T | null`; `id` is never optional on a read row; `table.extra` adds properties (the timestamps).
   */
  members(schema: Schema, indent: string, omitReadOnly: boolean, table?: TableMode): string[] {
    const props: Schema = { ...(table?.extra ?? {}), ...(isRecord(schema.properties) ? schema.properties : {}) };
    const required = new Set(Array.isArray(schema.required) ? schema.required.filter((r): r is string => typeof r === 'string') : []);
    const lines: string[] = [];
    for (const name of Object.keys(props).sort(byKey)) {
      const p = props[name];
      if (omitReadOnly && isRecord(p) && p.readOnly === true) continue;
      const doc = isRecord(p) ? this.jsdoc(p) : '';
      if (doc !== '') lines.push(`${indent}/** ${doc} */`);
      let t = this.type(p, indent);
      let optional = !required.has(name);
      if (table !== undefined && optional) {
        if (table.kind === 'read' && name === 'id') optional = false;
        else t = withNull(t);
      }
      lines.push(`${indent}${propKey(name)}${optional ? '?' : ''}: ${t};`);
    }
    const extra = this.additional(schema, indent);
    // With named properties a typed index signature would have to cover them all: widen it to unknown.
    if (extra !== null) lines.push(`${indent}[key: string]: ${Object.keys(props).length > 0 ? 'unknown' : extra};`);
    return lines;
  }

  /** Type of `additionalProperties`, or null when it adds nothing. */
  private additional(schema: Schema, indent: string): string | null {
    const ap = schema.additionalProperties;
    if (ap === undefined || ap === false) return null;
    if (ap === true) return 'unknown';
    return this.type(ap, indent);
  }

  private object(schema: Schema, indent: string, omitReadOnly: boolean): string {
    const props = isRecord(schema.properties) ? Object.keys(schema.properties) : [];
    if (props.length === 0) {
      // A bare `type: object` is how the backend documents a JSON column, which may hold any JSON value.
      const extra = this.additional(schema, indent);
      return extra === null ? 'unknown' : `Record<string, ${extra}>`;
    }
    const inner = this.members(schema, `${indent}  `, omitReadOnly);
    // Short members without comments stay on one line.
    if (inner.every((l) => !l.trimStart().startsWith('/**')) && inner.join(' ').length < 80) {
      return `{ ${inner.map((l) => l.trim().replace(/;$/, '')).join('; ')} }`;
    }
    return `{\n${inner.join('\n')}\n${indent}}`;
  }

  jsdoc(s: Schema): string {
    const parts: string[] = [];
    if (typeof s.description === 'string' && s.description.trim() !== '') parts.push(commentText(s.description));
    if (typeof s.format === 'string' && s.format !== '' && s.$ref === undefined) {
      const format = `format: ${commentText(s.format)}`;
      parts.push(parts.length === 0 ? format : `(${format})`);
    }
    return parts.join(' ');
  }

  /** A top-level declaration for one named schema. */
  declaration(name: string, omitReadOnly: boolean, table?: TableMode): string {
    const schema = this.schemas[name];
    const id = ident(name);
    const doc = isRecord(schema) ? this.jsdoc(schema) : '';
    const head = doc === '' ? '' : `/** ${doc} */\n`;
    if (isRecord(schema) && schema.$ref === undefined && schema.nullable !== true && !Array.isArray(schema.enum)) {
      const isObject = schema.type === 'object' || (schema.type === undefined && isRecord(schema.properties));
      const props = isRecord(schema.properties) ? Object.keys(schema.properties) : [];
      if (isObject && props.length > 0 && schema.allOf === undefined && schema.oneOf === undefined && schema.anyOf === undefined) {
        return `${head}export interface ${id} {\n${this.members(schema, '  ', omitReadOnly, table).join('\n')}\n}\n`;
      }
    }
    return `${head}export type ${id} = ${this.type(schema, '', omitReadOnly)};\n`;
  }
}

/** Every `$ref` string anywhere under `v`. */
function collectRefs(v: unknown, out: Set<string>): void {
  if (Array.isArray(v)) {
    for (const x of v) collectRefs(x, out);
  } else if (isRecord(v)) {
    for (const [k, x] of Object.entries(v)) {
      if (k === '$ref' && typeof x === 'string') out.add(x);
      else collectRefs(x, out);
    }
  }
}

/**
 * Table name for each `{Name}` base. The backend names schemas `schemaName(table)` and serves the table at
 * `/{apiPrefix}/{table}...`; a path segment `s` with `schemaName(s) === Name` on a path that references
 * `{Name}Read` / `{Name}Write` is the table. Without such a path (a table with every operation off), the
 * lowercased `Name` is used, which is the table name for the usual lowercase table names.
 */
function tableNames(bases: string[], paths: Record<string, unknown>): Map<string, string> {
  const found = new Map<string, string>();
  for (const path of Object.keys(paths).sort(byKey)) {
    const refs = new Set<string>();
    collectRefs(paths[path], refs);
    for (const seg of path.split('/')) {
      if (seg === '' || seg.startsWith('{')) continue;
      const base = schemaName(seg);
      if (found.has(base)) continue;
      if (refs.has(`${REF_PREFIX}${base}Read`) || refs.has(`${REF_PREFIX}${base}Write`)) found.set(base, seg);
    }
  }
  const out = new Map<string, string>();
  for (const base of bases) out.set(base, found.get(base) ?? base.toLowerCase());
  return out;
}

/**
 * Generates TypeScript declarations from an sp-laravel-api OpenAPI document: one interface per
 * `{Name}Read` / `{Name}Write` component schema pair, every schema they reference, and
 * `interface Tables { <table>: { read: <Name>Read; write: <Name>Write } }` for `createApi<Tables>()`.
 *
 * Output is deterministic (sorted, no timestamps). In the table schemas a property outside `required` is
 * `name?: T | null` (the backend's `required` means "non-nullable column"; it emits no `nullable` flag), `id`
 * is never optional in `{Name}Read`, and `{Name}Read` gains `created_at` / `updated_at` from the full `{Name}`
 * schema. Elsewhere optional follows `required` and `| null` follows `nullable: true` or a `'null'` type.
 * `readOnly` properties are left out of the `Write` types (the backend ignores them on write). Throws
 * `TypegenError` for anything that is not such a document, an unresolved `$ref` or a name collision.
 */
export function generateTypes(doc: unknown): string {
  if (!isRecord(doc) || (typeof doc.openapi !== 'string' && typeof doc.swagger !== 'string')) {
    throw new TypegenError('input is not an OpenAPI document (no "openapi" version field)');
  }
  const components = isRecord(doc.components) ? doc.components : {};
  const schemas = isRecord(components.schemas) ? components.schemas : {};
  const bases = Object.keys(schemas)
    .filter((k) => k.endsWith('Read') && k.length > 4 && Object.prototype.hasOwnProperty.call(schemas, `${k.slice(0, -4)}Write`))
    .map((k) => k.slice(0, -4))
    .sort(byKey);
  if (bases.length === 0) {
    throw new TypegenError('no {Name}Read/{Name}Write component schemas found (is this an sp-laravel-api document?)');
  }

  const gen = new Generator(schemas);
  const tables = tableNames(bases, isRecord(doc.paths) ? doc.paths : {});
  const blocks: string[] = [];
  const emitted = new Set<string>();
  for (const base of bases) {
    // Rows carry the timestamps that `{Name}Read` leaves out: take them from the full `{Name}` schema when it
    // documents them (OpenApiService::tableSchema keeps created_at / updated_at; tableSchemaRead drops them).
    const full = schemas[base];
    const fullProps = isRecord(full) && isRecord(full.properties) ? full.properties : {};
    const extra: Schema = {};
    for (const ts of ['created_at', 'updated_at']) if (fullProps[ts] !== undefined) extra[ts] = fullProps[ts];
    emitted.add(`${base}Read`);
    blocks.push(gen.declaration(`${base}Read`, false, { kind: 'read', extra }));
    emitted.add(`${base}Write`);
    blocks.push(gen.declaration(`${base}Write`, true, { kind: 'write' }));
  }
  // Schemas reached through $ref, until no new reference appears (references can chain and cycle).
  const extraBlocks = new Map<string, string>();
  for (;;) {
    const pending = [...gen.referenced].filter((n) => !emitted.has(n)).sort(byKey);
    if (pending.length === 0) break;
    for (const name of pending) {
      emitted.add(name);
      extraBlocks.set(name, gen.declaration(name, false));
    }
  }
  for (const name of [...extraBlocks.keys()].sort(byKey)) blocks.push(extraBlocks.get(name) as string);

  // Two schemas mapping to one identifier (or to `Tables`) would produce a file that does not compile.
  const owners = new Map<string, string>([['Tables', '(the generated Tables interface)']]);
  for (const name of [...emitted].sort(byKey)) {
    const id = ident(name);
    const other = owners.get(id);
    if (other !== undefined) {
      throw new TypegenError(`name collision: schema ${quote(name)} and ${other.startsWith('(') ? other : `schema ${quote(other)}`} both generate ${id}`);
    }
    owners.set(id, name);
  }

  const rows = [...tables.entries()]
    .map(([base, table]) => ({ table, base }))
    .sort((a, b) => byKey(a.table, b.table))
    .map(({ table, base }) => `  ${propKey(table)}: { read: ${ident(`${base}Read`)}; write: ${ident(`${base}Write`)} };`);

  const info = isRecord(doc.info) ? doc.info : {};
  const title = typeof info.title === 'string' ? commentText(info.title) : '';
  const version = typeof doc.openapi === 'string' ? doc.openapi : String(doc.swagger);
  const source = `// Source: ${title === '' ? 'OpenAPI document' : title} (OpenAPI ${commentText(version)}).`;

  return [
    `${HEADER}\n${source}\n// Table columns not in \`required\` (sp-laravel-api: nullable columns) are typed \`name?: T | null\`.\n`,
    ...blocks,
    `/** Table name -> row (\`read\`) and write (\`write\`) types. Use as \`createApi<Tables>(config)\`. */\nexport interface Tables {\n${rows.join('\n')}\n}\n`,
  ].join('\n');
}
